def test_persisted_result_artifacts_have_canonical_row_order(
    tmp_path,
    monkeypatch,
):
    monkeypatch.setenv("ICAPA_WORKSPACE_ROOT", str(tmp_path))
    workspace = ResearchWorkspace.open("canonical_result_artifacts")
    run = workspace.run(_spec(_SnapshotMethodology()))
    assert run.simulation is not None

    reordered_reviews = {}
    for effective_date, context in reversed(tuple(run.backtest.reviews.items())):
        reordered = context.copy()
        reordered._df = context.cons.iloc[::-1].copy()
        reordered_reviews[effective_date] = reordered
    reordered_backtest = BacktestResult(
        weights=run.backtest.weights.iloc[::-1],
        reviews=reordered_reviews,
        metadata=run.backtest.metadata,
    )
    reordered_simulation = replace(
        run.simulation,
        daily=run.simulation.daily.iloc[::-1],
        holdings=run.simulation.holdings.iloc[::-1],
        rebalances=run.simulation.rebalances.iloc[::-1],
        asset_returns=run.simulation.asset_returns.iloc[::-1],
        weight_snapshots=run.simulation.weight_snapshots.iloc[::-1],
    )

    original = workspace._save_result_artifacts(
        run.backtest,
        run.simulation,
        run.analytics,
    )
    reordered = workspace._save_result_artifacts(
        reordered_backtest,
        reordered_simulation,
        run.analytics,
    )

    assert {
        item.artifact_type: item.content_digest for item in original
    } == {
        item.artifact_type: item.content_digest for item in reordered
    }
