class _SyntheticProvider:
    """Stable offline data whose snapshot identity is generated by the provider."""

    def research_data_identity(self, *, capability, request):
        _IDENTITY_CALLS["provider"] += 1
        return {
            "dataset": "synthetic_research",
            "revision": 1,
            "capability": capability,
        }

    def load_universe(
        self,
        universe_id,
        reference_date,
        effective_date,
        **kwargs,
    ):
        _CALLS["universe"] += 1
        weights = (
            np.array([0.45, 0.35, 0.20])
            if pd.Timestamp(effective_date).month == 6
            else np.array([0.35, 0.40, 0.25])
        )
        return pd.DataFrame(
            {
                "instrument_id": ["A", "B", "C"],
                "name": ["Alpha", "Beta", "Gamma"],
                "country": ["US", "US", "CA"],
                "industry": ["Technology", "Industrials", "Technology"],
                "shares": [100.0, 120.0, 80.0],
                "free_float": [0.9, 0.8, 0.95],
                "price": [20.0, 30.0, 25.0],
                "currency": ["USD", "USD", "CAD"],
                "base_currency": ["USD", "USD", "USD"],
                "fx_rate": [1.0, 1.0, 0.75],
                "market_cap": [1800.0, 2880.0, 1425.0],
                "benchmark_weight": weights,
                "reference_date": [pd.Timestamp(reference_date)] * 3,
                "effective_date": [pd.Timestamp(effective_date)] * 3,
            }
        )

    def load_daily_market_data(
        self,
        instrument_ids,
        start_date,
        end_date,
        **kwargs,
    ):
        _CALLS["market"] += 1
        rows = []
        for date_offset, business_date in enumerate(
            pd.bdate_range(start_date, end_date)
        ):
            for instrument_offset, instrument_id in enumerate(instrument_ids):
                rows.append(
                    {
                        "instrument_id": instrument_id,
                        "business_date": business_date,
                        "price_return": (
                            0.0002
                            + 0.00005 * instrument_offset
                            + 0.00001 * (date_offset % 5)
                        ),
                        "gross_dividend": 0.00001,
                        "net_dividend": 0.000008,
                        "market_cap": (
                            1_000_000.0
                            * (instrument_offset + 1)
                            * (1.0 + 0.001 * date_offset)
                        ),
                    }
                )
        return pd.DataFrame.from_records(rows)


@dataclass(frozen=True)
class _SnapshotMethodology:
    universe_id: str = "SYNTHETIC"
    universe_provider_name: str = _PROVIDER_NAME

