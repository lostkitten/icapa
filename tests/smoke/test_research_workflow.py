def test_high_level_pipeline_defaults_to_uncached_lightweight_results(
    tmp_path,
    monkeypatch,
):
    monkeypatch.setenv("ICAPA_WORKSPACE_ROOT", str(tmp_path))
    workspace = ResearchWorkspace.open("high_level_default")

    run = workspace.run(_spec(_SnapshotMethodology(), report=True))

    assert _CALLS == {"universe": 2, "market": 2}
    assert run.manifest.status == "complete"
    assert len(run.manifest.execution_id) == 32
    assert len(run.manifest.definition_fingerprint) == 64
    assert len(run.manifest.result_fingerprint) == 64
    assert run.simulation is not None
    assert run.simulation.holdings.empty
    assert run.simulation.asset_returns.empty
    assert (
        run.simulation.metadata["calculation_mode"]
        == "calendar_month_partitions"
    )
    assert run.analytics is not None
    assert len(run.review_status) == 2
    assert set(run.review_status["status"]) == {"complete"}
    assert run.report is not None
    assert run.report.path.is_dir()
    assert {
        item["input_type"] for item in run.manifest.input_digests
    } == {
        "analytics_calculation_inputs",
        "source_daily_market_data",
    }

    coverage = workspace.coverage()
    assert coverage.iloc[0]["label"] == "baseline"
    assert coverage.iloc[0]["tags"] == ("demo", "research")
    assert coverage.iloc[0]["artifact_count"] > 0
    assert coverage.iloc[0]["research_status"] == "draft"
    assert workspace.latest() == run.manifest
    assert workspace.open_run(run.manifest_ref) == run.manifest
    assert workspace.verify().ok
    assert workspace.rebuild_catalog().registered == 1
    assert workspace.prune().dry_run
    assert workspace.set_status(run, ResearchStatus.IN_REVIEW) is (
        ResearchStatus.IN_REVIEW
    )
    assert workspace.get_status(run) is ResearchStatus.IN_REVIEW

    workspace.invalidate(run)
    assert workspace.latest() is None
    assert workspace.list() == ()
    assert workspace.list(include_invalidated=True) == (run.manifest_ref,)


